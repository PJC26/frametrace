// Builds a synthetic dashcam-style SOURCE folder (not a case) for demos and
// screenshots. Needs ffmpeg on PATH (or FFMPEG=/path/to/ffmpeg).
//
//   node scripts/make-demo-case.mjs <out-dir> [--clean]
//
// Produces short, visually distinct H.264 clips named like real dashcam
// output (generic FRONT/REAR, Thinkware, BlackVue, Garmin-style), spread over
// two days and several folders, plus one truncated (corrupt) clip and one
// zero-byte clip so the review UI has interesting findings to show.
// Fully synthetic: no real footage, plates or people.
import { mkdirSync, rmSync, existsSync, writeFileSync, truncateSync, statSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { spawnSync } from 'node:child_process';

const args = process.argv.slice(2);
const out = args.find((a) => !a.startsWith('--'));
if (!out) { console.error('usage: node scripts/make-demo-case.mjs <out-dir> [--clean]'); process.exit(2); }
const ffmpeg = process.env.FFMPEG || 'ffmpeg';
if (spawnSync(ffmpeg, ['-version']).status !== 0) {
  console.error('ffmpeg not found. Install it (apt-get install ffmpeg / brew install ffmpeg) or set FFMPEG=...');
  process.exit(1);
}
if (args.includes('--clean') && existsSync(out)) rmSync(out, { recursive: true, force: true });

// [relative path, lavfi source, seconds, audio?]
const clips = [
  ['DCIM/FRONT/FRONT_20260908_010000.mp4', 'testsrc2=size=640x360:rate=15', 4, true],
  ['DCIM/FRONT/FRONT_20260908_010400.mp4', 'smptebars=size=640x360:rate=15', 4, true],
  ['DCIM/FRONT/FRONT_20260908_010800.mp4', 'mandelbrot=size=640x360:rate=15', 4, false],
  ['DCIM/REAR/REAR_20260908_010000.mp4', 'life=size=640x360:rate=15:mold=10:ratio=0.1:death_color=#202040:life_color=#40c0ff', 4, false],
  ['DCIM/REAR/REAR_20260908_010400.mp4', 'testsrc=size=640x360:rate=15', 4, false],
  ['Thinkware/REC_2026_09_08_23_15_00_F.MP4', 'testsrc2=size=1280x720:rate=15', 3, true],
  ['Thinkware/REC_2026_09_08_23_15_00_R.MP4', 'smptehdbars=size=640x360:rate=15', 3, true],
  ['BlackVue/20260909_083000_NF.mp4', 'mandelbrot=size=1280x720:rate=15', 3, true],
  ['BlackVue/20260909_083000_NR.mp4', 'rgbtestsrc=size=640x360:rate=15', 3, false],
  ['Event/EVT_20260909_171204_IMPACT.mp4', 'testsrc2=size=640x360:rate=15,hue=h=120', 3, true],
];

let made = 0;
for (const [rel, src, secs, audio] of clips) {
  const file = join(out, rel);
  mkdirSync(dirname(file), { recursive: true });
  const a = ['-y', '-v', 'error', '-f', 'lavfi', '-i', src];
  if (audio) a.push('-f', 'lavfi', '-i', 'sine=frequency=440', '-c:a', 'aac', '-shortest');
  a.push('-t', String(secs), '-c:v', 'libx264', '-pix_fmt', 'yuv420p', '-preset', 'ultrafast', '-movflags', '+faststart', file);
  const r = spawnSync(ffmpeg, a, { encoding: 'utf8' });
  if (r.status !== 0) { console.error(`ffmpeg failed for ${rel}\n${r.stderr}`); process.exit(1); }
  made++;
}

// Damaged clips: cut a valid file in half (moov at front survives, mdat is
// short) and an empty placeholder.
const damaged = join(out, 'DCIM/FRONT/FRONT_20260908_011200.mp4');
spawnSync(ffmpeg, ['-y', '-v', 'error', '-f', 'lavfi', '-i', 'testsrc2=size=640x360:rate=15', '-t', '4', '-c:v', 'libx264', '-pix_fmt', 'yuv420p', '-preset', 'ultrafast', damaged]);
if (existsSync(damaged)) { truncateSync(damaged, Math.floor(statSync(damaged).size / 2)); made++; }
writeFileSync(join(out, 'DCIM/REAR/REAR_20260908_011200.mp4'), '');
made++;
writeFileSync(join(out, 'README-demo.txt'), 'Synthetic dashcam demo folder generated by scripts/make-demo-case.mjs. No real footage.\n');
console.log(`demo source ready: ${out} (${made} clips)`);
