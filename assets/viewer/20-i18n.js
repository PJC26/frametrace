// R10 U5: is this mount showing a bundle's trust codes (computed on the PC
// that generated it, 10-boot trustFromBundle)? false outside a mount.
function viewerTrustFromBundle() {
  try { return trustFromBundle === true; } catch { return false; }
}
// R10 U5: a trust text that says "이 PC" has a "<key>@bundle" twin
// ("생성 PC 기준") used when the trust codes came from a bundle.
function trustI18nKey(key) {
  return viewerTrustFromBundle() && Object.prototype.hasOwnProperty.call(I18N.ko, key + "@bundle") ? key + "@bundle" : key;
}

function t(key) {
  key = trustI18nKey(key);
  let locale = storageGet(LOCALE_KEY, "ko") || "ko";
  // `state` is a top-level const initialized after the record maps that
  // call t() run — touching it in its TDZ throws ReferenceError, so the
  // access must be guarded rather than assumed initialized.
  try {
    if (state && state.locale) locale = state.locale;
  } catch { /* state not initialized yet */ }
  return (I18N[locale] && I18N[locale][key]) || (I18N.ko[key]) || key;
}

// tf formats a locale string with {name} placeholders.
function tf(key, subs) {
  let s = t(key);
  if (subs) for (const [name, value] of Object.entries(subs)) {
    s = s.split("{" + name + "}").join(String(value));
  }
  return s;
}

// R8 U6: a text that follows the language switch — the key (and its {name}
// values, data-i18n-args JSON) ride on the element; applyChromeI18n()
// (every render, the language button) re-renders it. Notices built at run
// time (90-sync notices row) use it instead of a one-off textContent.
function i18nText(el, key, subs) {
  if (!el) return el;
  el.dataset.i18n = key;
  if (subs) el.dataset.i18nArgs = JSON.stringify(subs);
  else delete el.dataset.i18nArgs;
  const text = subs ? tf(key, subs) : t(key);
  if (el.textContent !== text) el.textContent = text;
  return el;
}

function applyChromeI18n() {
  document.documentElement.lang = state.locale;
  ftRoot.querySelectorAll("[data-i18n]").forEach(el => {
    let subs = null;
    if (el.dataset.i18nArgs) { try { subs = JSON.parse(el.dataset.i18nArgs); } catch (e) { subs = null; } }
    const text = subs ? tf(el.dataset.i18n, subs) : t(el.dataset.i18n);
    if (el.textContent !== text) el.textContent = text;
  });
  ftRoot.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    el.setAttribute("placeholder", t(el.dataset.i18nPlaceholder));
  });
  ftRoot.querySelectorAll("[data-i18n-title]").forEach(el => {
    el.setAttribute("title", t(el.dataset.i18nTitle));
  });
  ftRoot.querySelectorAll("[data-i18n-aria-label]").forEach(el => {
    el.setAttribute("aria-label", t(el.dataset.i18nAriaLabel));
  });
  const langBtn = document.getElementById("btnLang");
  if (langBtn) langBtn.textContent = state.locale === "ko" ? "EN" : "KO";
}
